def _slug(text: str) -> str:
    """Lower-case ASCII version of a name part, for building an email address."""
    folded = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]+", ".", folded.lower()).strip(".")


def _year_month(index: int) -> str:
    """Convert a month counter (year * 12 + zero-based month) to 'YYYY-MM'."""
    year, month = divmod(index, 12)
    return f"{year}-{month + 1:02d}"


def _work_history(
    rng: random.Random, family: Family, level: int, ref_year: int, skill_pool: list[str]
) -> tuple[list[Record], int]:
    """Build the jobs, newest first, and return them with the total months worked."""
    seniority = SENIORITIES[level]
    low, high = YEARS_RANGE[seniority]
    total_months = int(rng.uniform(low, high) * 12)
    count = min(rng.randint(*JOB_COUNT[seniority]), max(1, total_months // 8))
    weights = [rng.uniform(0.6, 1.6) for _ in range(count)]
    scale = total_months / sum(weights)
    months = [max(6, round(weight * scale)) for weight in weights]

    today = ref_year * 12 + 8  # September of the reference year
    jobs: list[Record] = []
    job_level = level
    newer_start: int | None = None
    for i, company in enumerate(rng.sample(COMPANIES, count)):
        if newer_start is None:
            is_current = rng.random() < 0.8
            end = today if is_current else today - rng.randint(1, 6)
        else:
            is_current = False
            end = newer_start - rng.randint(0, 3)
            if rng.random() < 0.75:
                job_level = max(0, job_level - 1)
        start = end - months[i]

        bullets = []
        for template in rng.sample(family.bullets, rng.randint(2, 4)):
            text = template.format(n=rng.randrange(10, 50, 5), m=rng.randint(2, 8))
            if rng.random() < 0.6:
                text += f" ({', '.join(rng.sample(skill_pool, 2))})"
            bullets.append(text)

        jobs.append(
            {
                "title": family.titles[job_level],
                "company": company,
                "years": round(months[i] / 12, 1),
                "summary": bullets[0],
                "start": _year_month(start),
                "end": None if is_current else _year_month(end),
                "bullets": bullets,
            }
        )
        newer_start = start
    return jobs, sum(months)


def _education(
    rng: random.Random, family: Family, level: int, first_job_year: int
) -> list[Record]:
    grad_year = first_job_year - rng.randint(0, 1)
    schools = rng.sample(INSTITUTIONS, 2)
    field = rng.choice(family.fields)
    if level >= 1 and rng.random() < 0.4:
        return [
            {
                "degree": f"{family.master} {field}",
                "institution": schools[0],
                "grad_year": grad_year,
            },
            {
                "degree": f"{family.bachelor} {rng.choice(family.fields)}",
                "institution": schools[1],
                "grad_year": grad_year - 2,
            },
        ]
    return [
        {"degree": f"{family.bachelor} {field}", "institution": schools[0], "grad_year": grad_year}
    ]


def _summary(rng: random.Random, headline: str, years: float, skills: list[str]) -> str:
    if years < 1:
        span = "under a year"
    else:
        span = f"{int(years)} year{'' if int(years) == 1 else 's'}"
    first, second, third = skills[:3]
    closer = rng.choice(SUMMARY_CLOSERS)
    return rng.choice(
        (
            f"{headline} with {span} of experience in {first}, {second} and {third}. {closer}",
            f"{span.capitalize()} of hands-on work with {first} and {second}, "
            f"most recently as {headline}. {closer}",
            f"My most recent role is {headline}; most of my work involves {first}, {second} "
            f"and {third}. {closer}",
        )
    )


def build_cv(
    index: int, seed: int, ref_year: int, fakers: dict[str, Faker]
) -> tuple[Record, Record]:
    """Return the ground truth for one CV and the options used to draw its PDF.

    Each CV has its own random stream, so CV number N is the same whatever --cvs is.
    """
    rng = random.Random(f"{seed}:cv:{index}")
    family = FAMILIES[index % len(FAMILIES)]
    seniority = CV_SENIORITY_CYCLE[index % len(CV_SENIORITY_CYCLE)]
    layout = LAYOUT_CYCLE[index % len(LAYOUT_CYCLE)]
    level = SENIORITIES.index(seniority)
    candidate_id = f"C{index + 1:03d}"

    fake = fakers[rng.choice(LOCALES)]
    fake.seed_instance(rng.getrandbits(32))
    first_name, last_name = fake.first_name(), fake.last_name()
    local_part = ".".join(part for part in (_slug(first_name), _slug(last_name)) if part)
    local_part = local_part or "candidate"
    if rng.random() < 0.4:
        local_part += str(rng.randint(1, 99))
    email = f"{local_part}@{rng.choice(EMAIL_DOMAINS)}"
    phone = f"+1-{rng.choice(AREA_CODES)}-555-01{rng.randint(0, 99):02d}"
    location = rng.choice(CITIES)

    low, high = CORE_SKILL_COUNT[seniority]
    core = rng.sample(family.core, rng.randint(low, high))
    extra = rng.sample(family.extra, rng.randint(1, 3))
    other_family = rng.choice([f for f in FAMILIES if f.key != family.key])
    unrelated = rng.sample(other_family.core, rng.randint(0, 2))
    soft = rng.sample(SOFT_SKILLS, rng.randint(0, 2))
    skills = list(dict.fromkeys(core + extra + unrelated + soft))
    rng.shuffle(skills)

    history, total_months = _work_history(rng, family, level, ref_year, core + extra)
    experience_years = round(total_months / 12, 1)
    education = _education(rng, family, level, int(history[-1]["start"][:4]))
    headline = history[0]["title"]

    languages = [f"English ({rng.choice(('native', 'fluent', 'C1'))})"]
    for language in rng.sample(LANGUAGES, rng.randint(0, 2)):
        languages.append(f"{language} ({rng.choice(LANGUAGE_LEVELS)})")
    certifications = rng.sample(family.certs, rng.randint(0, len(family.certs)))

    # Some real CVs carry details a scorer must never use. A few synthetic ones do
    # too, so tests can check that the parser and scorer leave them out.
    sensitive_noise = None
    if rng.random() < 0.15:
        birth_year = education[-1]["grad_year"] - rng.randint(21, 24)
        sensitive_noise = {
            "date_of_birth": f"{rng.randint(1, 28)} {rng.choice(MONTH_NAMES)} {birth_year}",
            "nationality": rng.choice(NATIONALITIES),
        }

    cv = {
        "candidate_id": candidate_id,
        "synthetic": True,
        "full_name": f"{first_name} {last_name}",
        "email": email,
        "phone": phone,
        "location": location,
        "headline": headline,
        "role_family": family.key,
        "seniority": seniority,
        "layout": layout,
        "pdf_file": f"{candidate_id}.pdf",
        "summary": _summary(rng, headline, experience_years, core),
        "languages": languages,
        "certifications": certifications,
        # Same shape as candidates.parsed_data in the API, plus start, end and bullets per job.
        "parsed_data": {
            "skills": skills,
            "experience_years": experience_years,
            "education": education,
            "work_history": history,
        },
        "sensitive_noise": sensitive_noise,
    }
    options = {
        "font": "Courier" if layout == "plain" else rng.choice(("Helvetica", "Times-Roman")),
        "size": rng.choice((9.0, 9.5, 10.0)),
        "date_style": rng.choice(("year", "month_year", "numeric")),
        "bullet": rng.choice(("•", "-", "–")),
        "headings": {key: rng.choice(choices) for key, choices in HEADINGS.items()},
        "skills_style": rng.choice(("commas", "bullets", "pipes")),
        "skills_first": rng.random() < 0.3,
        "sidebar_left": rng.random() < 0.7,
    }
    return cv, options


# --------------------------------------------------------------------------- PDF layouts


def _doc_args(cv: Record) -> Record:
    """Settings shared by every layout.

    `invariant` fixes the timestamps and document ID, and switching compression off
    removes the dependency on the local zlib build, so the bytes are repeatable.
    """
    return {
        "pagesize": A4,
        "title": f"Synthetic CV {cv['candidate_id']}",
        "author": "ats-scorer synthetic data generator",
        "subject": "Synthetic test data. Not a real person.",
        "invariant": 1,
        "pageCompression": 0,
    }


def _styles(options: Record, shrink: float = 0.0) -> Styles:
    font = options["font"]
    bold = FONTS[font]
    size = options["size"] - shrink
    grey = colors.HexColor("#555555")
    return {
        "name": ParagraphStyle(
            "name", fontName=bold, fontSize=size + 9, leading=size + 13, spaceAfter=2
        ),
        "headline": ParagraphStyle(
            "headline",
            fontName=font,
            fontSize=size + 2,
            leading=size + 6,
            textColor=grey,
            spaceAfter=4,
        ),
        "heading": ParagraphStyle(
            "heading",
            fontName=bold,
            fontSize=size + 1.5,
            leading=size + 5,
            spaceBefore=9,
            spaceAfter=3,
        ),
        "body": ParagraphStyle("body", fontName=font, fontSize=size, leading=size + 3.5),
        "small": ParagraphStyle(
            "small", fontName=font, fontSize=size - 1, leading=size + 2, textColor=grey
        ),
        "right": ParagraphStyle(
            "right", fontName=font, fontSize=size - 1, leading=size + 2, alignment=TA_RIGHT
        ),
        "bullet": ParagraphStyle(
            "bullet",
            fontName=font,
            fontSize=size,
            leading=size + 3.5,
            leftIndent=10,
            bulletIndent=1,
            bulletFontName=font,
            bulletFontSize=size,
        ),
    }


def _p(text: str, style: ParagraphStyle) -> Paragraph:
    """Paragraph from plain text, escaped so '&' or '<' in the data cannot break the markup."""
    return Paragraph(escape(text), style)


def _bullets(items: list[str], options: Record, style: ParagraphStyle) -> list[Flowable]:
    return [Paragraph(escape(item), style, bulletText=options["bullet"]) for item in items]


def _contact(cv: Record) -> list[str]:
    return [cv["email"], cv["phone"], cv["location"]]


def _format_date(value: str | None, style: str) -> str:
    if value is None:
        return "Present"
    year, month = value.split("-")
    if style == "year":
        return year
    if style == "numeric":
        return f"{month}/{year}"
    return f"{MONTH_ABBR[int(month) - 1]} {year}"


def _date_range(job: Record, style: str) -> str:
    return f"{_format_date(job['start'], style)} - {_format_date(job['end'], style)}"


def _noise_block(cv: Record, st: Styles) -> list[Flowable]:
    noise = cv["sensitive_noise"]
    if not noise:
        return []
    line = f"Date of birth: {noise['date_of_birth']} | Nationality: {noise['nationality']}"
    return [_p(line, st["small"])]


def _experience_block(cv: Record, options: Record, st: Styles) -> list[Flowable]:
    out: list[Flowable] = []
    for job in cv["parsed_data"]["work_history"]:
        title_line = f"<b>{escape(job['title'])}</b>, {escape(job['company'])}"
        out.append(Paragraph(title_line, st["body"]))
        out.append(_p(_date_range(job, options["date_style"]), st["small"]))
        out += _bullets(job["bullets"], options, st["bullet"])
        out.append(Spacer(1, 5))
    return out


def _skills_block(cv: Record, options: Record, st: Styles) -> list[Flowable]:
    skills = cv["parsed_data"]["skills"]
    if options["skills_style"] == "bullets":
        return _bullets(skills, options, st["bullet"])
    separator = " | " if options["skills_style"] == "pipes" else ", "
    return [_p(separator.join(skills), st["body"])]


def _education_block(cv: Record, st: Styles) -> list[Flowable]:
    out: list[Flowable] = []
    for entry in cv["parsed_data"]["education"]:
        out.append(Paragraph(f"<b>{escape(entry['degree'])}</b>", st["body"]))
        out.append(_p(f"{entry['institution']}, {entry['grad_year']}", st["small"]))
    return out


def _extras_block(cv: Record, options: Record, st: Styles) -> list[Flowable]:
    headings = options["headings"]
    out = [_p(headings["languages"], st["heading"]), _p(", ".join(cv["languages"]), st["body"])]
    if cv["certifications"]:
        out.append(_p(headings["certifications"], st["heading"]))
        out += [_p(name, st["body"]) for name in cv["certifications"]]
    return out


def render_classic(cv: Record, options: Record, path: Path) -> None:
    """Single column with clear headings: the easy case for a parser."""
    st = _styles(options)
    headings = options["headings"]
    doc = SimpleDocTemplate(
        str(path),
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=16 * mm,
        **_doc_args(cv),
    )
    skills = [_p(headings["skills"], st["heading"]), *_skills_block(cv, options, st)]
    experience = [_p(headings["experience"], st["heading"]), *_experience_block(cv, options, st)]
    story = [
        _p(cv["full_name"], st["name"]),
        _p(cv["headline"], st["headline"]),
        _p(" | ".join(_contact(cv)), st["small"]),
        *_noise_block(cv, st),
        _p(headings["summary"], st["heading"]),
        _p(cv["summary"], st["body"]),
    ]
    story += skills + experience if options["skills_first"] else experience + skills
    story += [_p(headings["education"], st["heading"]), *_education_block(cv, st)]
    story += _extras_block(cv, options, st)
    doc.build(story)


def render_two_column(cv: Record, options: Record, path: Path) -> None:
    """Shaded sidebar next to the main column.

    The sidebar is written to the PDF first even when it sits on the right, so the
    order of the text in the file does not always match left-to-right reading order.
    """
    st = _styles(options)
    side_st = _styles(options, shrink=1.0)
    headings = options["headings"]
    page_width, page_height = A4
    margin, gutter, side_width = 12 * mm, 6 * mm, 60 * mm
    main_width = page_width - 2 * margin - gutter - side_width
    frame_height = page_height - 2 * margin
    if options["sidebar_left"]:
        side_x, main_x = margin, margin + side_width + gutter
    else:
        main_x, side_x = margin, margin + main_width + gutter

    def shade_sidebar(canvas: Any, _doc: Any) -> None:
        canvas.saveState()
        canvas.setFillColor(colors.HexColor("#EEF1F5"))
        canvas.rect(side_x - 2 * mm, 0, side_width + 4 * mm, page_height, stroke=0, fill=1)
        canvas.restoreState()

    doc = BaseDocTemplate(str(path), **_doc_args(cv))
    doc.addPageTemplates(
        [
            PageTemplate(
                id="first",
                frames=[
                    Frame(side_x, margin, side_width, frame_height, id="side"),
                    Frame(main_x, margin, main_width, frame_height, id="main"),
                ],
                onPage=shade_sidebar,
            ),
            # Later pages continue the main column only.
            PageTemplate(id="rest", frames=[Frame(main_x, margin, main_width, frame_height)]),
        ]
    )
    sidebar = [
        _p("Contact", side_st["heading"]),
        *[_p(line, side_st["body"]) for line in _contact(cv)],
        *_noise_block(cv, side_st),
        _p(headings["skills"], side_st["heading"]),
        *_bullets(cv["parsed_data"]["skills"], options, side_st["bullet"]),
        _p(headings["education"], side_st["heading"]),
        *_education_block(cv, side_st),
        *_extras_block(cv, options, side_st),
    ]
    main = [
        _p(cv["full_name"], st["name"]),
        _p(cv["headline"], st["headline"]),
        _p(headings["summary"], st["heading"]),
        _p(cv["summary"], st["body"]),
        _p(headings["experience"], st["heading"]),
        *_experience_block(cv, options, st),
    ]
    doc.build([NextPageTemplate("rest"), *sidebar, FrameBreak(), *main])


def render_table(cv: Record, options: Record, path: Path) -> None:
    """Header, experience, skills and education as tables, with dates in their own column."""
    st = _styles(options)
    headings = options["headings"]
    margin = 16 * mm
    width = A4[0] - 2 * margin - 12  # the frame adds 6pt of padding on each side
    doc = SimpleDocTemplate(
        str(path),
        leftMargin=margin,
        rightMargin=margin,
        topMargin=margin,
        bottomMargin=margin,
        **_doc_args(cv),
    )
    flush = [
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
    ]

    contact = "<br/>".join(escape(line) for line in _contact(cv))
    header = Table(
        [
            [
                [_p(cv["full_name"], st["name"]), _p(cv["headline"], st["headline"])],
                Paragraph(contact, st["right"]),
            ]
        ],
        colWidths=[width * 0.62, width * 0.38],
    )
    header.setStyle(TableStyle([*flush, ("LINEBELOW", (0, 0), (-1, -1), 0.8, colors.black)]))

    date_width = 36 * mm
    rows = []
    for job in cv["parsed_data"]["work_history"]:
        details = [
            Paragraph(f"<b>{escape(job['title'])}</b>", st["body"]),
            _p(job["company"], st["small"]),
            *_bullets(job["bullets"], options, st["bullet"]),
        ]
        rows.append([_p(_date_range(job, options["date_style"]), st["small"]), details])
    experience = Table(rows, colWidths=[date_width, width - date_width])
    experience.setStyle(
        TableStyle(
            [
                *flush,
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.lightgrey),
            ]
        )
    )

    columns = 3
    skills = list(cv["parsed_data"]["skills"])
    skills += [""] * (-len(skills) % columns)
    grid = Table(
        [skills[i : i + columns] for i in range(0, len(skills), columns)],
        colWidths=[width / columns] * columns,
    )
    grid.setStyle(
        TableStyle(
            [
                ("FONT", (0, 0), (-1, -1), options["font"], options["size"] - 0.5),
                ("GRID", (0, 0), (-1, -1), 0.25, colors.lightgrey),
            ]
        )
    )

    education = Table(
        [
            [str(entry["grad_year"]), _p(f"{entry['degree']}, {entry['institution']}", st["body"])]
            for entry in cv["parsed_data"]["education"]
        ],
        colWidths=[date_width, width - date_width],
    )
    education.setStyle(
        TableStyle([*flush, ("FONT", (0, 0), (0, -1), options["font"], options["size"] - 1)])
    )

    story = [
        header,
        *_noise_block(cv, st),
        _p(headings["summary"], st["heading"]),
        _p(cv["summary"], st["body"]),
        _p(headings["experience"], st["heading"]),
        experience,
        _p(headings["skills"], st["heading"]),
        grid,
        _p(headings["education"], st["heading"]),
        education,
        *_extras_block(cv, options, st),
    ]
    doc.build(story)


def render_plain(cv: Record, options: Record, path: Path) -> None:
    """Typewriter style: no bold headings, bullets run together, contact details at the end."""
    st = _styles(options)
    body = st["body"]
    data = cv["parsed_data"]
    doc = SimpleDocTemplate(
        str(path),
        leftMargin=22 * mm,
        rightMargin=22 * mm,
        topMargin=20 * mm,
        bottomMargin=20 * mm,
        **_doc_args(cv),
    )
    story: list[Flowable] = [
        _p(cv["full_name"].upper(), body),
        _p(cv["headline"], body),
        _p("-" * 48, body),
        _p(cv["summary"], body),
        *_noise_block(cv, st),
        Spacer(1, 8),
        _p("WHERE I HAVE WORKED", body),
    ]
    for job in data["work_history"]:
        dates = _date_range(job, options["date_style"])
        story.append(_p(f"{job['title']} at {job['company']} ({dates})", body))
        story.append(_p(". ".join(job["bullets"]) + ".", body))
        story.append(Spacer(1, 6))
    studied = "; ".join(
        f"{entry['degree']}, {entry['institution']}, {entry['grad_year']}"
        for entry in data["education"]
    )
    story += [
        _p("Tools and skills: " + " / ".join(data["skills"]), body),
        Spacer(1, 6),
        _p("Studied: " + studied, body),
        _p("Speaks: " + ", ".join(cv["languages"]), body),
    ]
    if cv["certifications"]:
        story.append(_p("Certificates: " + "; ".join(cv["certifications"]), body))
    story += [Spacer(1, 8), _p("Reach me: " + ", ".join(_contact(cv)), body)]
    doc.build(story)


