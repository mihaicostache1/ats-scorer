def _join(items: list[str]) -> str:
    """'a', 'a and b' or 'a, b and c'."""
    if len(items) < 2:
        return "".join(items)
    return f"{', '.join(items[:-1])} and {items[-1]}"


def _job_description(
    rng: random.Random,
    title: str,
    department: str,
    location: str,
    min_years: int,
    required: list[str],
    preferred: list[str],
    duties: list[str],
) -> str:
    if min_years == 0:
        experience = "No professional experience needed; internships and personal projects count"
    else:
        plural = "" if min_years == 1 else "s"
        experience = f"At least {min_years} year{plural} of relevant experience"

    style = rng.choice(("sections", "prose", "terse"))
    if style == "sections":
        lines = [
            "About the role",
            f"We are hiring a {title} for our {department} team ({location}).",
            "",
            "What you will do",
            *[f"- {duty}" for duty in duties],
            "",
            "What you bring",
            f"- {experience}",
            f"- Solid working knowledge of {_join(required)}",
            "",
            "Nice to have",
            f"- {_join(preferred)}",
        ]
        return "\n".join(lines)
    if style == "prose":
        tasks = _join([duty[0].lower() + duty[1:] for duty in duties])
        return (
            f"Our {department} team is growing and we are looking for a {title}. "
            f"You will {tasks}. {experience}. You should be confident with {_join(required)}. "
            f"Experience with {_join(preferred)} is a plus. Location: {location}."
        )
    return "\n".join(
        [
            f"{title} - {location}",
            f"Must have: {', '.join(required)}",
            f"Experience: {experience}",
            f"Good to have: {', '.join(preferred)}",
            f"Tasks: {'; '.join(duties)}",
        ]
    )


def build_job(index: int, seed: int) -> Record:
    """Return one job description, using the same field names as the jobs API."""
    rng = random.Random(f"{seed}:job:{index}")
    family = FAMILIES[index % len(FAMILIES)]
    seniority = JOB_SENIORITY_CYCLE[index % len(JOB_SENIORITY_CYCLE)]
    title = family.titles[SENIORITIES.index(seniority)]
    required = rng.sample(family.core, rng.randint(4, 6))
    remaining = [skill for skill in family.core + family.extra if skill not in required]
    preferred = rng.sample(remaining, rng.randint(2, 4))
    min_years = MIN_EXPERIENCE[seniority] + rng.randint(0, 1)
    location = rng.choice(JOB_LOCATIONS)
    employment_type = rng.choices(("full_time", "part_time", "contract"), weights=(8, 1, 2))[0]
    duties = rng.sample(family.duties, rng.randint(3, 4))
    return {
        "job_id": f"J{index + 1:02d}",
        "synthetic": True,
        "title": title,
        "department": family.department,
        "location": location,
        "employment_type": employment_type,
        "description": _job_description(
            rng, title, family.department, location, min_years, required, preferred, duties
        ),
        "required_skills": required,
        "preferred_skills": preferred,
        "min_experience_years": min_years,
        "role_family": family.key,
        "seniority": seniority,
    }


def build_rating_pairs(
    cvs: list[Record], jobs: list[Record], seed: int, per_job: int
) -> list[tuple[str, str]]:
    """Pick the (candidate_id, job_id) pairs people are asked to rate.

    About two thirds of each job's candidates come from the job's own family, so the
    ratings cover the whole 0-3 scale instead of being mostly zeros.
    """
    pairs: list[tuple[str, str]] = []
    for job in jobs:
        rng = random.Random(f"{seed}:pairs:{job['job_id']}")
        same = [cv["candidate_id"] for cv in cvs if cv["role_family"] == job["role_family"]]
        other = [cv["candidate_id"] for cv in cvs if cv["role_family"] != job["role_family"]]
        same_count = min(len(same), (per_job * 2 + 2) // 3)
        other_count = min(len(other), per_job - same_count)
        chosen = rng.sample(same, same_count) + rng.sample(other, other_count)
        pairs += [(candidate_id, job["job_id"]) for candidate_id in sorted(chosen)]
    return pairs


