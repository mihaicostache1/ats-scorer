def _write_json(path: Path, data: Any) -> None:
    text = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    path.write_text(text, encoding="utf-8", newline="\n")


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _clear(directory: Path, patterns: tuple[str, ...]) -> None:
    """Remove files from an earlier run. Only touches the file names this script writes."""
    for pattern in patterns:
        for old_file in directory.glob(pattern):
            old_file.unlink()


def _positive(value: str) -> int:
    number = int(value)
    if number < 1:
        raise argparse.ArgumentTypeError("must be 1 or more")
    return number


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--seed", type=int, default=42, help="random seed (default: 42)")
    parser.add_argument("--cvs", type=_positive, default=100, help="number of CVs (default: 100)")
    parser.add_argument(
        "--jobs", type=_positive, default=20, help="number of job descriptions (default: 20)"
    )
    parser.add_argument(
        "--pairs-per-job",
        type=_positive,
        default=15,
        help="candidates to rate for each job (default: 15)",
    )
    parser.add_argument(
        "--year",
        type=int,
        default=2026,
        help="year treated as 'now' for work history dates (default: 2026)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parent / "output",
        help="output directory (default: ./output next to this script)",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    cv_dir, job_dir = args.out / "cvs", args.out / "jobs"
    cv_dir.mkdir(parents=True, exist_ok=True)
    job_dir.mkdir(parents=True, exist_ok=True)
    _clear(cv_dir, ("C*.pdf", "C*.json"))
    _clear(job_dir, ("J*.json",))

    fakers = {locale: Faker(locale) for locale in LOCALES}
    cvs = []
    cv_entries = []
    for index in range(args.cvs):
        cv, options = build_cv(index, args.seed, args.year, fakers)
        pdf_path = cv_dir / cv["pdf_file"]
        RENDERERS[cv["layout"]](cv, options, pdf_path)
        _write_json(cv_dir / f"{cv['candidate_id']}.json", cv)
        cvs.append(cv)
        cv_entries.append(
            {
                "candidate_id": cv["candidate_id"],
                "role_family": cv["role_family"],
                "seniority": cv["seniority"],
                "layout": cv["layout"],
                "pdf": f"cvs/{cv['pdf_file']}",
                "json": f"cvs/{cv['candidate_id']}.json",
                "pdf_sha256": _sha256(pdf_path),
            }
        )

    jobs = [build_job(index, args.seed) for index in range(args.jobs)]
    for job in jobs:
        _write_json(job_dir / f"{job['job_id']}.json", job)

    pairs = build_rating_pairs(cvs, jobs, args.seed, args.pairs_per_job)
    with open(args.out / "ratings_template.csv", "w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["candidate_id", "job_id", "rating"])
        writer.writerows([candidate_id, job_id, ""] for candidate_id, job_id in pairs)

    _write_json(
        args.out / "manifest.json",
        {
            "generator_version": GENERATOR_VERSION,
            "seed": args.seed,
            "reference_year": args.year,
            "packages": {
                "Faker": metadata.version("Faker"),
                "reportlab": metadata.version("reportlab"),
            },
            "counts": {"cvs": len(cvs), "jobs": len(jobs), "rating_pairs": len(pairs)},
            "cvs": cv_entries,
            "jobs": [
                {
                    "job_id": job["job_id"],
                    "role_family": job["role_family"],
                    "seniority": job["seniority"],
                    "json": f"jobs/{job['job_id']}.json",
                }
                for job in jobs
            ],
        },
    )

    print(
        f"Wrote {len(cvs)} CVs, {len(jobs)} jobs and {len(pairs)} rating pairs "
        f"to {args.out} (seed {args.seed})"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
